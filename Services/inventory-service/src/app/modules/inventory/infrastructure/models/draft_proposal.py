from datetime import datetime, timezone
from sqlalchemy import BigInteger, Column, DateTime, Index, Integer, String, Text
from sqlalchemy.orm import validates

from app.shared.core.database import Base


class DraftProposalModel(Base):
    """
    Draft proposals generated by AI Agent or human operators requiring
    two-man rule approval before executing mutations (Maker-Checker / SOX Compliance).
    """
    __tablename__ = "draft_proposals"

    VALID_STATUSES = {"DRAFT_PROPOSAL", "APPROVED", "REJECTED", "EXECUTED", "CANCELLED"}
    VALID_TRANSITIONS = {
        "DRAFT_PROPOSAL": {"APPROVED", "REJECTED", "CANCELLED"},
        "APPROVED": {"EXECUTED", "REJECTED", "CANCELLED"},
        "REJECTED": set(),  # Terminal state: cannot transition back
        "EXECUTED": set(),  # Terminal state: cannot transition back
        "CANCELLED": set(),  # Terminal state: cannot transition back
    }

    proposal_id = Column(String(64), primary_key=True)
    proposal_type = Column(String(64), nullable=False)
    sku_code = Column(String(64), nullable=False, index=True)
    warehouse_id = Column(Integer, nullable=False, default=1, index=True)
    location_code = Column(String(50), nullable=True, index=True)
    position_id = Column(BigInteger, nullable=True)
    current_quantity = Column(Integer, nullable=True)
    proposed_quantity = Column(Integer, nullable=True)
    adjustment = Column(Integer, nullable=True)
    reason = Column(Text, nullable=True)
    requested_by = Column(String(64), nullable=True, index=True)
    status = Column(String(32), nullable=False, default="DRAFT_PROPOSAL")
    created_at = Column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
        index=True,
    )

    # Maker-Checker Governance & Audit fields (TASK-058 / CRIT-08)
    approved_by = Column(String(64), nullable=True)
    approved_at = Column(DateTime(timezone=True), nullable=True)
    rejection_reason = Column(Text, nullable=True)
    executed_at = Column(DateTime(timezone=True), nullable=True)
    executed_by = Column(String(64), nullable=True)
    digital_signature = Column(String(128), nullable=True)

    __table_args__ = (
        Index("ix_draft_proposals_status", "status"),
        Index("ix_draft_proposals_wh_sku", "warehouse_id", "sku_code"),
    )

    @validates("status")
    def validate_status_transition(self, key, new_status):
        if not new_status:
            return "DRAFT_PROPOSAL"
        new_status = new_status.upper()
        if new_status not in self.VALID_STATUSES:
            raise ValueError(f"Invalid status '{new_status}'. Must be one of {self.VALID_STATUSES}")

        current_status = getattr(self, "status", None)
        if current_status and current_status != new_status:
            allowed_next = self.VALID_TRANSITIONS.get(current_status, set())
            if new_status not in allowed_next:
                raise ValueError(
                    f"Invalid status transition from {current_status} to {new_status}. "
                    f"Terminal states (REJECTED, EXECUTED) cannot transition back to DRAFT_PROPOSAL."
                )
        return new_status

    def approve(self, approver: str = "", approved_by: str = "", digital_signature: str = None) -> None:
        """Approve the proposal by a warehouse manager."""
        self.status = "APPROVED"
        self.approved_by = approved_by or approver
        self.approved_at = datetime.now(timezone.utc)
        if digital_signature:
            self.digital_signature = digital_signature

    def reject(self, reason: str = "", rejection_reason: str = "", reviewer: str = None, rejected_by: str = None) -> None:
        """Reject the proposal with a reason."""
        self.status = "REJECTED"
        self.rejection_reason = rejection_reason or reason
        rev = rejected_by or reviewer
        if rev:
            self.approved_by = rev
            self.approved_at = datetime.now(timezone.utc)

    def mark_executed(self, executor: str = "", executed_by: str = "") -> None:
        """Mark the proposal as executed in inventory."""
        self.status = "EXECUTED"
        self.executed_by = executed_by or executor
        self.executed_at = datetime.now(timezone.utc)

    def cancel(self, canceller: str = "", cancelled_by: str = "", cancellation_reason: str = "") -> None:
        """Cancel the proposal by its creator (Maker Cancel / TASK-070)."""
        self.status = "CANCELLED"
        self.rejection_reason = cancellation_reason or f"Cancelled by maker {cancelled_by or canceller}"
        user = cancelled_by or canceller
        if user:
            self.approved_by = user
            self.approved_at = datetime.now(timezone.utc)
